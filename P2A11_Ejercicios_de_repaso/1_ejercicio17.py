"""
17. Escribir un programa para:
    a. Sumar dos números enteros.
    b. Restar dos números enteros.
    c. Multiplicar dos números enteros.
    d. Dividir un número entero por otro
"""

print("Introduce dos números enteros:")
a = int(input())
b = int(input())

print("---------------------")
print(f"{a} + {b} = {a + b}")
print(f"{a} - {b} = {a - b}")
print(f"{a} * {b} = {a * b}")
print(f"{a} / {b} = {a / b}")
