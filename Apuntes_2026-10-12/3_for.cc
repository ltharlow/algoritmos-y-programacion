#include <iostream>
using namespace std;

int main() {
    int numero;

    // Para i <- 1 hasta 10 hacer con paso 1
    for (numero=1; numero <= 10; numero++) { // numero = numero + 1
        cout << numero << endl;
    }

    return 0;
}
