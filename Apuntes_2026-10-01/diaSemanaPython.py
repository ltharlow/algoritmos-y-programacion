# Dia de la semana

print("Ingrese un número del 1 al 7: ")
Dia = int(input())

if Dia == 1:
    print("Lunes")
elif Dia == 2:
    print("Martes")
elif Dia == 3:
    print("Miércoles")
elif Dia == 4:
    print("Jueves")
elif Dia == 5:
    print("Viernes")
elif Dia == 6:
    print("Sábado")
elif Dia == 7:
    print("Domingo")
else:
    print("Número inválido")
